// Generates release/launch/archive-seed.sql from the collector's seed rules and keywords
// (edge-functions/_shared/archive/seed-rules.mjs, the one source of truth; docs/ARCHIVE_SPEC.md §8 "Seeds").
//   node scripts/archive-seed-sql.mjs          writes the file
//   node scripts/archive-seed-sql.mjs --check  exits 1 when the committed file is out of date
// The SQL is idempotent and keyed by (kind, name) for rules and (term, language) for keywords. It updates the
// definition of a seeded row in place and inserts missing rows; it works with or without unique indexes on those
// keys (an UPDATE … FROM, then an INSERT … WHERE NOT EXISTS, in one statement each). It never touches what operators
// and the scheduler own: a rule's enabled flag, verified_at and scheduling state, or a keyword's enabled flag.
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { SEED_RULES, SEED_KEYWORDS } from '../edge-functions/_shared/archive/seed-rules.mjs'

const root = path.resolve(import.meta.dirname, '..')
export const SEED_SQL_PATH = path.join(root, 'release/launch/archive-seed.sql')

/** @param {unknown} v */
const lit = (v) => v === null || v === undefined ? 'null' : typeof v === 'boolean' ? String(v) : typeof v === 'number' ? String(Math.trunc(v)) : `'${String(v).replace(/'/g, "''")}'`

/** The seed SQL text (deterministic: same seeds → same bytes). */
export function seedSql() {
  const rules = SEED_RULES.map((r, i) => {
    const cast = i === 0
    const t = (/** @type {unknown} */ v) => lit(v) + (cast ? '::text' : '')
    return `  (${t(r.kind)}, ${t(r.name)}, ${t(r.query)}, ${t(r.url)}, ${t(r.language)}, ${t(r.region_hint)}, ${lit(r.enabled)}${cast ? '::boolean' : ''}, ${lit(r.cadence_hours)}${cast ? '::integer' : ''}, ${t(r.terms_url)}, ${t(r.notes)})`
  })
  const keywords = SEED_KEYWORDS.map((k, i) => {
    const cast = i === 0
    return `  (${lit(k.term)}${cast ? '::text' : ''}, ${lit(k.language)}${cast ? '::text' : ''}, ${lit(k.polarity)}${cast ? '::text' : ''}, ${lit(k.weight)}${cast ? '::integer' : ''})`
  })
  return `-- Archive collector seeds: collection rules and weighted keywords (docs/ARCHIVE_SPEC.md §2, §3, §8).
-- GENERATED by scripts/archive-seed-sql.mjs from edge-functions/_shared/archive/seed-rules.mjs; do not edit by hand.
-- Idempotent: run it again after a seed change. Seeded definitions are updated in place by (kind, name) and
-- (term, language); missing rows are inserted. Operator state is kept: rules keep enabled, verified_at and their
-- schedule; keywords keep enabled. Every source starts unverified (verified_at null) and keyed or metered sources
-- (NAVER, Brave) start disabled.
-- ${SEED_RULES.length} rules, ${SEED_KEYWORDS.length} keywords.

begin;

with seed(kind, name, query, url, language, region_hint, enabled, cadence_hours, terms_url, notes) as (values
${rules.join(',\n')}
), updated as (
  update public.archive_collection_rules r
     set query = s.query, url = s.url, language = s.language, region_hint = s.region_hint,
         cadence_hours = s.cadence_hours, terms_url = s.terms_url, notes = s.notes
    from seed s
   where r.kind = s.kind and r.name = s.name
  returning r.kind, r.name
)
insert into public.archive_collection_rules (kind, name, query, url, language, region_hint, enabled, cadence_hours, terms_url, verified_at, notes)
select s.kind, s.name, s.query, s.url, s.language, s.region_hint, s.enabled, s.cadence_hours, s.terms_url, null, s.notes
  from seed s
 where not exists (select 1 from public.archive_collection_rules r where r.kind = s.kind and r.name = s.name);

with seed(term, language, polarity, weight) as (values
${keywords.join(',\n')}
), updated as (
  update public.archive_keywords k
     set polarity = s.polarity, weight = s.weight
    from seed s
   where k.term = s.term and k.language = s.language
  returning k.term, k.language
)
insert into public.archive_keywords (term, language, polarity, weight, enabled)
select s.term, s.language, s.polarity, s.weight, true
  from seed s
 where not exists (select 1 from public.archive_keywords k where k.term = s.term and k.language = s.language);

commit;
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = seedSql()
  if (process.argv.includes('--check')) {
    const current = await readFile(SEED_SQL_PATH, 'utf8').catch(() => '')
    if (current !== text) { console.error('release/launch/archive-seed.sql is out of date: run npm run archive:seed-sql'); process.exit(1) }
    console.log('archive-seed.sql is up to date.')
  } else {
    await writeFile(SEED_SQL_PATH, text)
    console.log(`Wrote ${path.relative(root, SEED_SQL_PATH)}: ${SEED_RULES.length} rules, ${SEED_KEYWORDS.length} keywords.`)
  }
}
