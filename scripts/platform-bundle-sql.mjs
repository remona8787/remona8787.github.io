// Writes release/launch/platform-v2.sql: the v2.0 platform migrations in install order, in one transaction, for a
// project that already has release/launch/complete-backend.sql (docs/PLATFORM.md section 6). Each migration is carried
// verbatim after a "-- SOURCE: migrations/<file>" line (its own begin;/commit; lines left out). Every migration in it
// can run again, so the bundle can too. tests/platform-bundle.test.mjs checks that the file matches the migrations.
// Run after every change to one of them: npm run platform:bundle-sql (or with --check to only compare).
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
export const PLATFORM_MIGRATIONS=['20261026000000_research_data.sql','20261112000000_v2_platform.sql','20261113000000_v2_photo_grades.sql','20261113010000_v2_admin_members.sql','20261113020000_v2_permission_ledger.sql','20261114000000_v2_submission_followup.sql'];
export const BUNDLE='release/launch/platform-v2.sql';
export async function platformBundle(){
 const parts=['-- v2.0 member, researcher and community platform (docs/PLATFORM.md). Generated by scripts/platform-bundle-sql.mjs;',
  '-- do not edit by hand. Apply after release/launch/complete-backend.sql, in the SQL editor or with the platform',
  '-- workflow (.github/workflows/platform.yml). One transaction: on an error nothing is changed. Safe to run again.',
  'begin;'];
 for(const f of PLATFORM_MIGRATIONS){
  const sql=await readFile(path.join(root,'supabase/migrations',f),'utf8');
  parts.push('','-- SOURCE: migrations/'+f,sql.split('\n').filter(l=>!['begin;','commit;'].includes(l.trim())).join('\n').trim());
 }
 parts.push('','commit;','');
 return parts.join('\n');
}
if(import.meta.url===`file://${process.argv[1]}`){
 const out=await platformBundle(),file=path.join(root,BUNDLE);
 const cur=await readFile(file,'utf8').catch(()=>null);
 if(process.argv.includes('--check')){if(cur!==out){console.error(BUNDLE+' is out of date: npm run platform:bundle-sql');process.exit(1)}console.log(BUNDLE+' matches the migrations')}
 else if(cur===out)console.log(BUNDLE+' already up to date');
 else{await writeFile(file,out);console.log('Wrote '+BUNDLE)}
}
